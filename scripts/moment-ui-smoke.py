"""Actual radio selection, optional fields and three moment types on emulator-5580."""
from pathlib import Path
import importlib.util
spec=importlib.util.spec_from_file_location('diary_ui_helpers',Path(__file__).with_name('diary-ui-smoke.py'))
ui=importlib.util.module_from_spec(spec);spec.loader.exec_module(ui)
ui.OUT=ui.ROOT/'build/moment-ui-smoke';ui.OUT.mkdir(parents=True,exist_ok=True)
ui.launch()
ui.tap('Zapisz trudny moment',scroll=True)
for label in ('Czułem napięcie','Zareagowałem impulsywnie','Rozmowa się zaostrzyła'):
 ui.verify(ui.find(label).get('checked')=='false','new moment does not invent a type: '+label)
ui.shot('moment-types')
ui.tap('Zareagowałem impulsywnie');ui.tap('ZAPISZ')
ui.check('Zareagowałem impulsywnie','impulsive reaction saves with optional fields left empty',contains=True,scroll=True)
ui.tap('Zareagowałem impulsywnie',contains=True);ui.tap('Popraw trudny moment')
ui.verify(ui.find('Zareagowałem impulsywnie').get('checked')=='true','editor restores selected impulse radio')
ui.verify(ui.find('Czułem napięcie').get('checked')=='false','other radio is not selected while editing impulse')
ui.tap('Rozmowa się zaostrzyła');ui.tap('ZAPISZ')
ui.check('Rozmowa się zaostrzyła','edited conversation type appears in diary',contains=True,scroll=True)
ui.tap('Rozmowa się zaostrzyła',contains=True);ui.tap('Popraw trudny moment')
ui.verify(ui.find('Rozmowa się zaostrzyła').get('checked')=='true','editor restores selected escalation radio')
ui.tap('Czułem napięcie');ui.tap('ZAPISZ')
ui.tap('Spokojny dzień',scroll=True);ui.check('✓ Spokojny dzień','reclassified tension allows a new calm check-in')
ui.tap('Czułem napięcie',contains=True,scroll=True);ui.tap('Popraw trudny moment')
ui.verify(ui.find('Czułem napięcie').get('checked')=='true','editor restores selected tension radio')
ui.tap('ANULUJ');ui.tap('Czułem napięcie',contains=True,scroll=True);ui.tap('Usuń wpis');ui.tap('ZOSTAW')
ui.check('Czułem napięcie','moment deletion can be cancelled',contains=True)
ui.tap('Czułem napięcie',contains=True);ui.tap('Usuń wpis');ui.tap('USUŃ')
ui.verify(not any(' · Czułem napięcie' in n.get('text','') for n in ui.nodes()),'confirmed deletion removes chosen moment')
ui.check('✓ Spokojny dzień','removing a moment retains calm check-in')
print('PASS:',len(ui.passed),'moment type and editor UI checks',flush=True)
